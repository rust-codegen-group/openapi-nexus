//! Project metadata and explicit Python package re-exports shared by both transports.

use std::collections::BTreeSet;

use heck::{ToPascalCase, ToSnakeCase};
use indexmap::IndexMap;
use sigil_stitch::lang::python::Python;
use sigil_stitch::prelude::*;

use super::PYTHON_LINE_LENGTH;
use crate::codegen::traits::file_writer::FileInfo;
use crate::generators::request_inputs::RequestInputModel;
use crate::ir::types::{IrInfo, IrOperation, IrSchema};

pub(super) fn render_file_header(info: &IrInfo) -> String {
    let mut header = String::from("# Code generated by openapi-nexus. DO NOT EDIT.\n#\n");
    let metadata = format!("{} — {}", info.title, info.version);
    let lines = metadata
        .lines()
        .chain(info.description.as_deref().into_iter().flat_map(str::lines));
    for line in lines.map(str::trim_end) {
        header.push('#');
        if !line.is_empty() {
            header.push(' ');
            header.push_str(line);
        }
        header.push('\n');
    }
    header.push('\n');
    header
}

#[expect(
    clippy::too_many_arguments,
    reason = "shares the two existing backend entrypoints"
)]
pub(super) fn generate_project_files(
    info: &IrInfo,
    package_name: &str,
    header: &str,
    schemas: &IndexMap<String, IrSchema>,
    operations: &[IrOperation],
    request_inputs: &[RequestInputModel],
    include_upload_file: bool,
    dependency: &str,
) -> Vec<FileInfo> {
    let filename = format!("{package_name}/__init__.py");
    let runtime_exports = [
        "ApiKeyAuth",
        "Authenticator",
        "BearerAuth",
        "ApiResponse",
        "Client",
        "ApiError",
    ]
    .into_iter()
    .chain(include_upload_file.then_some("UploadFile"))
    .map(|name| (".runtime".to_owned(), name.to_owned()));
    let model_exports = schemas
        .values()
        .map(|schema| schema.name.as_str())
        .chain(request_inputs.iter().map(|model| model.name.as_str()))
        .map(|name| (format!(".{}", name.to_snake_case()), name.to_pascal_case()));
    let tags: BTreeSet<&str> = operations
        .iter()
        .flat_map(|op| {
            op.tags
                .iter()
                .map(String::as_str)
                .chain(op.tags.is_empty().then_some("default"))
        })
        .collect();
    let api_exports = tags.into_iter().map(|tag| {
        (
            format!(".{}_api", tag.to_snake_case()),
            format!("{}Api", tag.to_pascal_case()),
        )
    });
    vec![
        pyproject_toml(info, package_name, dependency),
        readme_file(info, package_name),
        FileInfo::project(format!("{package_name}/py.typed"), String::new()),
        FileInfo::project(
            filename.clone(),
            render_barrel(&filename, header, runtime_exports),
        ),
        FileInfo::model(
            "__init__.py".to_string(),
            render_barrel("__init__.py", header, model_exports),
        ),
        FileInfo::api(
            "__init__.py".to_string(),
            render_barrel("__init__.py", header, api_exports),
        ),
    ]
}

fn render_barrel(
    filename: &str,
    header: &str,
    exports: impl IntoIterator<Item = (String, String)>,
) -> String {
    // The header is supplied by the caller and only contains file metadata.
    let mut file = FileSpec::builder_with(filename, Python::new()).header(
        sigil_quote!(Python { $L(header.trim_end()) }).expect("Python barrel header builds"),
    );
    for (module, name) in exports {
        // Explicit same-name aliases are public re-exports to Python type checkers.
        file = file.add_import(ImportSpec::named_as(&module, &name, &name));
    }
    file.build()
        .expect("Python export file builds")
        .render(PYTHON_LINE_LENGTH)
        .expect("Python export file renders")
}

fn pyproject_toml(info: &IrInfo, package_name: &str, dependency: &str) -> FileInfo {
    let description = info
        .description
        .as_deref()
        .unwrap_or("Generated Python SDK.")
        .lines()
        .next()
        .unwrap_or("Generated Python SDK.");
    let content = format!(
        r#"[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "{package_name}"
version = "{version}"
description = "{description}"
requires-python = ">=3.12"
dependencies = ["{dependency}"]
"#,
        version = info.version,
    );
    FileInfo::project("pyproject.toml".to_string(), content)
}

fn readme_file(info: &IrInfo, package_name: &str) -> FileInfo {
    let title = &info.title;
    let version = &info.version;
    let description = info
        .description
        .as_deref()
        .unwrap_or("Generated Python SDK.");
    let content = format!(
        "# {title}\n\n{description}\n\nVersion: `{version}`\n\nGenerated by [openapi-nexus](https://github.com/rust-codegen-group/openapi-nexus) for `{package_name}`.\n"
    );
    FileInfo::readme("README.md".to_string(), content)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn long_barrel_import_keeps_an_explicit_public_export() {
        let module = ".very_long_public_schema_name_for_nested_contracts";
        let name = "VeryLongPublicSchemaNameForNestedContracts";
        let source = render_barrel(
            "__init__.py",
            "# Generated test\n\n",
            [(module.into(), name.into())],
        );
        assert_eq!(
            source,
            format!("# Generated test\n\nfrom {module} import (\n    {name} as {name},\n)\n")
        );
    }
}
